import json

from app.core.config import settings
from app.core.errors import InferenceFailure, ModelUnavailable, ProviderRateLimited, ProviderTimeout
from app.core.store import ImageRecord
from app.schemas.cv import ReportRequest
from app.services.providers import chat_completion, provider_configured

LLM_NOTICES = {
    "not_requested": None,
    "not_configured": "No language-model provider is configured. This summary is assembled from stored results.",
    "timeout": "The language model timed out. This summary is assembled from stored results.",
    "failed": "The language model did not return a usable narrative. This summary is assembled from stored results.",
    "invalid_response": "The language-model response could not be validated, so it was discarded. This summary is assembled from stored results.",
    "ok": "This narrative was generated by a language model from the stored results. The observations are the recorded measurements.",
}


def build_grounded_report(record: ImageRecord, options: ReportRequest) -> tuple[dict, dict]:
    height, width = record.image.shape[:2]
    observations: list[str] = []
    interpretations: list[str] = []
    limitations: list[str] = []
    recommendations: list[str] = []
    evidence = {
        "image_width": int(width),
        "image_height": int(height),
        "color_space": record.color_space,
        "detection_count": None,
        "ocr_region_count": None,
        "segmentation_model": None,
        "similarity_model": None,
        "vlm_model": None,
        "classical_operations": [],
    }
    requested = any(
        [
            options.include_classical,
            options.include_detection,
            options.include_segmentation,
            options.include_ocr,
            options.include_similarity,
            options.include_vlm,
        ]
    )
    if not requested:
        limitations.append("No analysis sections were requested.")
        recommendations.append("Run an analysis, then include its stored result in the report.")

    if options.include_classical:
        runs = record.analyses.get("classical") or []
        if not runs:
            limitations.append("No classical image-processing operation is stored for this image.")
        else:
            names = [str(item["operation"]) for item in runs]
            evidence["classical_operations"] = names
            observations.append(
                "Classical operations stored for this image, in order: "
                + ", ".join(names)
                + ". These are deterministic transforms."
            )

    if options.include_detection:
        detection = record.analyses.get("detection")
        if detection is None:
            limitations.append("Object detection was not run, so this report has no detection records.")
            recommendations.append("Run object detection when you need classes and locations.")
        else:
            evidence["detection_count"] = detection["detection_count"]
            evidence["detection_model"] = detection["model"]
            if detection["detection_count"] == 0:
                observations.append(
                    f"Object detection ({detection['model']}) returned no objects at the confidence threshold of {detection['confidence_threshold']}."
                )
            else:
                parts = [
                    f"{item['label']} ({item['confidence']:.2f})"
                    for item in detection["detections"][:15]
                ]
                observations.append(
                    f"Object detection ({detection['model']}) returned {detection['detection_count']} object(s): "
                    + ", ".join(parts)
                    + "."
                )
                observations.append("Bounding boxes are absolute pixel coordinates on the decoded image, with x2 and y2 as exclusive edges.")

    if options.include_segmentation:
        segmentation = record.analyses.get("segmentation")
        if segmentation is None:
            limitations.append("Segmentation was not run, so this report has no mask summary.")
        else:
            evidence["segmentation_model"] = segmentation["model"]
            labels = [
                f"{item['label']} ({item['pixel_count']} px)"
                for item in segmentation["classes"][:8]
            ]
            observations.append(
                f"Segmentation ({segmentation['model']}, {segmentation['task']}) produced: "
                + ", ".join(labels)
                + "."
            )

    if options.include_ocr:
        ocr = record.analyses.get("ocr")
        if ocr is None:
            limitations.append("OCR was not run, so this report has no extracted text.")
        else:
            evidence["ocr_region_count"] = ocr["region_count"]
            if ocr["region_count"] == 0:
                observations.append(f"OCR ({ocr['model']}) ran and returned no text regions.")
            else:
                quotation = ocr["full_text"]
                shortened = False
                if len(quotation) > 500:
                    quotation = quotation[:500].rstrip()
                    shortened = True
                sentence = f"OCR ({ocr['model']}) returned {ocr['region_count']} text region(s). Combined text: {quotation}"
                if shortened:
                    sentence += " [quotation shortened]"
                observations.append(sentence)

    if options.include_similarity:
        similarity = record.analyses.get("similarity")
        if similarity is None:
            limitations.append("Image-text similarity was not run.")
        else:
            evidence["similarity_model"] = similarity["model"]
            ranked = [
                f"{item['rank']}. {item['text']} ({item['score']:.4f})"
                for item in similarity["rankings"]
            ]
            observations.append(
                f"Image-text similarity ({similarity['model']}) ranked the supplied phrases by cosine similarity: "
                + "; ".join(ranked)
                + ". These scores are not calibrated probabilities."
            )

    if options.include_vlm:
        vlm = record.analyses.get("vlm")
        if vlm is None:
            limitations.append("No vision-language answer is stored for this image.")
        else:
            evidence["vlm_model"] = vlm["model"]
            interpretations.append(f"Vision-language model {vlm['model']} answered: {vlm['answer']}")
            interpretations.append(
                "That answer is an interpretation from the vision-language model. It is separate from detector, segmentation, and OCR records."
            )

    summary = f"Grounded summary for a {width}×{height} {record.color_space} image."
    if observations:
        summary += f" {len(observations)} observation(s) come from stored analysis results."
    else:
        summary += " No stored measurements were included."
    if limitations:
        summary += " Unavailable sections are listed with the limitations."

    report = {
        "summary": summary,
        "observations": observations,
        "interpretations": interpretations,
        "limitations": limitations,
        "recommendations": recommendations,
        "user_observation": options.user_observation,
    }
    return report, evidence


async def compose_report(record: ImageRecord, options: ReportRequest) -> dict:
    report, evidence = build_grounded_report(record, options)
    llm_model = None
    narrative = None
    status = "not_requested"
    inference_ms = None
    if options.use_llm:
        llm_model = settings.llm_model
        if not provider_configured():
            status = "not_configured"
        else:
            status, narrative, inference_ms = await _narrative(report, evidence)
    return {
        "model": "grounded-report-v1",
        "llm_model": llm_model if options.use_llm else None,
        "llm_status": status,
        "llm_narrative": narrative,
        "llm_notice": LLM_NOTICES[status],
        "report": report,
        "evidence": evidence,
        "inference_ms": inference_ms,
    }


async def _narrative(report: dict, evidence: dict) -> tuple[str, str | None, float | None]:
    messages = [
        {
            "role": "system",
            "content": (
                "Write a short narrative from the supplied JSON only. "
                "Do not add objects, text, counts, coordinates, or metrics that are absent from the JSON. "
                "Return JSON with a single key named narrative."
            ),
        },
        {
            "role": "user",
            "content": json.dumps({"report": report, "evidence": evidence}, ensure_ascii=True),
        },
    ]
    try:
        text, elapsed = await chat_completion(
            messages,
            settings.llm_model,
            "No language-model provider is configured.",
        )
    except ModelUnavailable:
        return "not_configured", None, None
    except ProviderTimeout:
        return "timeout", None, None
    except (InferenceFailure, ProviderRateLimited):
        return "failed", None, None
    parsed = _extract_json(text)
    if not parsed or not isinstance(parsed.get("narrative"), str):
        return "invalid_response", None, elapsed
    narrative = parsed["narrative"].strip()
    if not narrative or len(narrative) > 2000:
        return "invalid_response", None, elapsed
    return "ok", narrative, elapsed


def _extract_json(text: str) -> dict | None:
    stripped = text.strip()
    if stripped.startswith("```"):
        stripped = stripped.strip("`")
        if stripped.lower().startswith("json"):
            stripped = stripped[4:].strip()
    try:
        value = json.loads(stripped)
    except json.JSONDecodeError:
        start = stripped.find("{")
        end = stripped.rfind("}")
        if start < 0 or end <= start:
            return None
        try:
            value = json.loads(stripped[start : end + 1])
        except json.JSONDecodeError:
            return None
    return value if isinstance(value, dict) else None
