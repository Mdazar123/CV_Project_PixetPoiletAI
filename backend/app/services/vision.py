import logging

import cv2
import numpy as np

from app.core.config import settings
from app.core.errors import InferenceFailure, ModelUnavailable
from app.services.providers import chat_completion, provider_configured
from app.utils.images import as_bgr

logger = logging.getLogger("pixelpilot.vision")
PROVIDER_MAX_SIDE = 768


def status() -> dict:
    configured = provider_configured()
    return {
        "configured": configured,
        "model": settings.vlm_model if configured else None,
        "reason": None if configured else "Set OPENAI_API_KEY to enable vision questions.",
    }


async def answer(image: np.ndarray, question: str) -> dict:
    if not provider_configured():
        raise ModelUnavailable(
            "No vision-language provider is configured. Set OPENAI_API_KEY on the server. No answer was generated."
        )
    encoded, resized = _jpeg(image)
    import base64

    data_url = "data:image/jpeg;base64," + base64.b64encode(encoded).decode("ascii")
    messages = [
        {
            "role": "system",
            "content": (
                "Answer questions about the attached image. Describe only what is visible. "
                "If text is unreadable, say so. If you are unsure, say you are unsure. "
                "Do not invent measurements or hidden details."
            ),
        },
        {
            "role": "user",
            "content": [
                {"type": "text", "text": question},
                {"type": "image_url", "image_url": {"url": data_url}},
            ],
        },
    ]
    try:
        text, inference_ms = await chat_completion(
            messages,
            settings.vlm_model,
            "No vision-language provider is configured. No answer was generated.",
            max_tokens=400,
        )
    except InferenceFailure:
        raise
    except Exception:
        logger.exception("vlm failed")
        raise
    note = "This answer was generated by a vision-language model and has not been independently verified."
    if resized:
        note += f" The image sent to the provider was reduced so its longest side is {PROVIDER_MAX_SIDE} pixels."
    return {
        "model": settings.vlm_model,
        "answer": text[:4000],
        "verified": False,
        "resized_for_provider": resized,
        "note": note,
        "inference_ms": inference_ms,
    }


def _jpeg(image: np.ndarray, max_side: int = PROVIDER_MAX_SIDE) -> tuple[bytes, bool]:
    view = as_bgr(image)
    height, width = view.shape[:2]
    resized = False
    longest = max(height, width)
    if longest > max_side:
        scale = max_side / longest
        view = cv2.resize(
            view,
            (max(1, int(round(width * scale))), max(1, int(round(height * scale)))),
            interpolation=cv2.INTER_AREA,
        )
        resized = True
    ok, buffer = cv2.imencode(".jpg", view, [int(cv2.IMWRITE_JPEG_QUALITY), 85])
    if not ok:
        raise InferenceFailure("The image could not be prepared for the vision-language model.")
    return buffer.tobytes(), resized
